import 'dart:convert';
import 'package:flutter/foundation.dart';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';
import 'package:flutter_web_auth_2/flutter_web_auth_2.dart';
import 'package:http/http.dart' as http;
import 'package:shared_preferences/shared_preferences.dart';
import '../config/feature_flags.dart';
import '../env/env.dart';

/// Strava OAuth 2.0 service.
///
/// Before shipping replace [clientId] and [clientSecret] with the credentials
/// from https://www.strava.com/settings/api.
/// The redirect URI must be registered as the "Authorization Callback Domain"
/// in your Strava API application — set it to `localhost` (Strava only checks
/// the domain, not the full URI for mobile apps).
class StravaService {
  StravaService._();

  static final StravaService instance = StravaService._();

  // ---------------------------------------------------------------------------
  // Strava API credentials — obfuscated constants generated by envied.
  // Optional: builds without a .env get empty strings and Strava stays hidden.
  // To enable it, copy .env.example → .env, fill in values, then run:
  //   dart run build_runner build --delete-conflicting-outputs
  // ---------------------------------------------------------------------------
  static String get clientId => Env.stravaClientId;
  static String get clientSecret => Env.stravaClientSecret;

  /// Whether this build has Strava API credentials compiled in.
  static bool get isConfigured => Env.hasStravaCredentials;

  /// Whether Strava should be offered in the UI: the feature flag is on *and*
  /// credentials are present. Gate every Strava entry point on this.
  static bool get isAvailable =>
      FeatureFlags.enableStravaUpload && isConfigured;
  static const String redirectUri = 'rideforge://localhost/exchange_token';
  static const String scope = 'activity:write,read';

  // ---------------------------------------------------------------------------
  // Storage keys
  // Tokens (sensitive) → flutter_secure_storage (Android Keystore / iOS Keychain)
  // Non-sensitive metadata → SharedPreferences
  // ---------------------------------------------------------------------------
  static const _secure = FlutterSecureStorage();
  static const String _secAccessToken = 'strava_access_token';
  static const String _secRefreshToken = 'strava_refresh_token';
  static const String _secExpiresAt = 'strava_expires_at';
  static const String _prefAthleteName = 'strava_athlete_name';
  static const String _prefAthleteId = 'strava_athlete_id';

  // ---------------------------------------------------------------------------
  // In-memory state
  // ---------------------------------------------------------------------------
  bool _isConnected = false;
  String? _athleteName;
  String? _accessToken;
  String? _refreshToken;
  int? _expiresAt; // Unix timestamp (seconds)

  bool get isConnected => _isConnected;
  String? get athleteName => _athleteName;

  // ---------------------------------------------------------------------------
  // Public API
  // ---------------------------------------------------------------------------

  /// Loads persisted credentials into memory.
  /// Tokens are read from secure storage; metadata from SharedPreferences.
  /// Call this once during app startup or when the settings screen opens.
  Future<void> loadCredentials() async {
    _accessToken = await _secure.read(key: _secAccessToken);
    _refreshToken = await _secure.read(key: _secRefreshToken);
    final expiresStr = await _secure.read(key: _secExpiresAt);
    _expiresAt = expiresStr != null ? int.tryParse(expiresStr) : null;

    final prefs = await SharedPreferences.getInstance();
    _athleteName = prefs.getString(_prefAthleteName);
    _isConnected = _accessToken != null;
  }

  /// Opens the Strava authorization page in a secure in-app browser, waits for
  /// the user to approve, then exchanges the returned code for tokens.
  ///
  /// Returns `true` on success, `false` if the user cancelled or an error occurred.
  Future<bool> authenticate() async {
    if (!isConfigured) {
      debugPrint(
        'StravaService: no credentials compiled in — see .env.example.',
      );
      return false;
    }
    try {
      final authUrl = _buildAuthorizationUrl();

      final result = await FlutterWebAuth2.authenticate(
        url: authUrl,
        callbackUrlScheme: 'rideforge',
      );

      final code = Uri.parse(result).queryParameters['code'];
      if (code == null || code.isEmpty) {
        debugPrint('StravaService: no code in callback URL: $result');
        return false;
      }

      return await exchangeCodeForToken(code);
    } on Exception catch (e) {
      debugPrint('StravaService: auth cancelled or failed: $e');
      return false;
    } catch (e) {
      debugPrint('StravaService: unexpected auth error: $e');
      return false;
    }
  }

  /// Exchanges a one-time authorization code for access + refresh tokens.
  Future<bool> exchangeCodeForToken(String code) async {
    try {
      final response = await http.post(
        Uri.parse('https://www.strava.com/oauth/token'),
        body: {
          'client_id': clientId,
          'client_secret': clientSecret,
          'code': code.trim(),
          'grant_type': 'authorization_code',
        },
      );

      if (response.statusCode == 200) {
        final data = jsonDecode(response.body) as Map<String, dynamic>;
        await _persistTokenData(data);
        return true;
      }
      debugPrint(
        'StravaService: token exchange failed ${response.statusCode}: ${response.body}',
      );
      return false;
    } catch (e) {
      debugPrint('StravaService: token exchange error: $e');
      return false;
    }
  }

  /// Uses the stored refresh token to obtain a new access token.
  Future<bool> refreshAccessToken() async {
    if (_refreshToken == null) return false;
    try {
      final response = await http.post(
        Uri.parse('https://www.strava.com/oauth/token'),
        body: {
          'client_id': clientId,
          'client_secret': clientSecret,
          'refresh_token': _refreshToken!,
          'grant_type': 'refresh_token',
        },
      );

      if (response.statusCode == 200) {
        final data = jsonDecode(response.body) as Map<String, dynamic>;
        await _persistTokenData(data);
        return true;
      }
      debugPrint(
        'StravaService: token refresh failed ${response.statusCode}: ${response.body}',
      );
      return false;
    } catch (e) {
      debugPrint('StravaService: token refresh error: $e');
      return false;
    }
  }

  /// Returns a valid access token, refreshing it first if it has expired.
  /// Returns `null` if not connected or if the refresh fails.
  Future<String?> getValidAccessToken() async {
    if (!_isConnected) return null;

    final nowSec = DateTime.now().millisecondsSinceEpoch ~/ 1000;
    if (_expiresAt != null && nowSec >= _expiresAt! - 60) {
      final refreshed = await refreshAccessToken();
      if (!refreshed) return null;
    }

    return _accessToken;
  }

  /// Clears all stored credentials and resets in-memory state.
  Future<void> disconnect() async {
    await _secure.delete(key: _secAccessToken);
    await _secure.delete(key: _secRefreshToken);
    await _secure.delete(key: _secExpiresAt);

    final prefs = await SharedPreferences.getInstance();
    await prefs.remove(_prefAthleteName);
    await prefs.remove(_prefAthleteId);

    _accessToken = null;
    _refreshToken = null;
    _expiresAt = null;
    _athleteName = null;
    _isConnected = false;
  }

  // ---------------------------------------------------------------------------
  // Private helpers
  // ---------------------------------------------------------------------------

  String _buildAuthorizationUrl() {
    final params = {
      'client_id': clientId,
      'response_type': 'code',
      'redirect_uri': redirectUri,
      'approval_prompt': 'force',
      'scope': scope,
    };
    return Uri.https('www.strava.com', '/oauth/authorize', params).toString();
  }

  Future<void> _persistTokenData(Map<String, dynamic> data) async {
    _accessToken = data['access_token'] as String?;
    _refreshToken = data['refresh_token'] as String?;
    _expiresAt = data['expires_at'] as int?;

    final athlete = data['athlete'] as Map<String, dynamic>?;
    if (athlete != null) {
      final first = (athlete['firstname'] as String?) ?? '';
      final last = (athlete['lastname'] as String?) ?? '';
      _athleteName = '$first $last'.trim();
    }

    _isConnected = _accessToken != null;

    // Tokens → secure storage (Android Keystore / iOS Keychain)
    if (_accessToken != null) {
      await _secure.write(key: _secAccessToken, value: _accessToken!);
    }
    if (_refreshToken != null) {
      await _secure.write(key: _secRefreshToken, value: _refreshToken!);
    }
    if (_expiresAt != null) {
      await _secure.write(key: _secExpiresAt, value: _expiresAt!.toString());
    }

    // Non-sensitive metadata → SharedPreferences
    final prefs = await SharedPreferences.getInstance();
    if (_athleteName != null) {
      await prefs.setString(_prefAthleteName, _athleteName!);
    }
    if (athlete?['id'] != null) {
      await prefs.setInt(_prefAthleteId, athlete!['id'] as int);
    }
  }
}
